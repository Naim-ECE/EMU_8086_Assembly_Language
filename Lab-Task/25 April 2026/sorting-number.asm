.MODEL SMALL
.STACK 100H
.DATA
ARR DB 5 DUP(?)  

MSG1 DB "Enter 5 numbers: $"
MSG2 DB 10,13,"Ascending: $"
MSG3 DB 10,13,"Descending: $"

.CODE
MAIN PROC
MOV AX, @DATA
MOV DS, AX

LEA DX, MSG1
MOV AH, 09H
INT 21H

MOV CX, 5
MOV SI, 0

INPUT_LOOP:
MOV AH, 01H
INT 21H
SUB AL, 30H           
MOV ARR[SI], AL
INC SI
LOOP INPUT_LOOP

MOV CX, 4

ASC1:
MOV SI, 0
MOV DX, 4

ASC2:
MOV AL, ARR[SI]
MOV BL, ARR[SI+1]
CMP AL, BL
JBE SKIP1

    
MOV ARR[SI], BL
MOV ARR[SI+1], AL

SKIP1:
INC SI
DEC DX
JNZ ASC2
LOOP ASC1
    
LEA DX, MSG2
MOV AH, 09H
INT 21H

MOV CX, 5
MOV SI, 0

PRINT1:
MOV DL, ARR[SI]
ADD DL, 30H
MOV AH, 02H
INT 21H
INC SI
LOOP PRINT1

MOV CX, 4

DESC1:
MOV SI, 0
MOV DX, 4

DESC2:
MOV AL, ARR[SI]
MOV BL, ARR[SI+1]
CMP AL, BL
JAE SKIP2

    
MOV ARR[SI], BL
MOV ARR[SI+1], AL

SKIP2:
INC SI
DEC DX
JNZ DESC2
LOOP DESC1

   
LEA DX, MSG3
MOV AH, 09H
INT 21H

MOV CX, 5
MOV SI, 0

PRINT2:
MOV DL, ARR[SI]
ADD DL, 30H
MOV AH, 02H
INT 21H
INC SI
LOOP PRINT2


MAIN ENDP
END MAIN
